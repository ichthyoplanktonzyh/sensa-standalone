export async function loadAdditionalMessages(locale:InterfaceLocale,namespace:TranslationNamespace):Promise<Messages>{
  const loader=loaders[locale]?.[namespace];
  if(!loader)throw new Error(`No bundled interface messages for ${locale}/${namespace}`);
  return (await loader()).default;
}
