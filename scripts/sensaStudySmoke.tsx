import assert from 'node:assert/strict';
import React, { act } from 'react';
import { Window } from 'happy-dom';
import { StudyScreen } from '../apps/web/src/experience/components/StudyScreen';
import { LearningTargetLibraryScreen } from '../apps/web/src/experience/components/learning/LearningTargetLibraryScreen';
import { checkinDateKey, readCheckinDates, recordCheckin } from '../apps/web/src/experience/components/StudyCalendar';
import { previewStorage } from '../apps/web/src/experience/services/previewStorage';
import i18n from '../apps/web/src/i18n';

async function main() {
  const window = new Window({url:'http://localhost:3000'});
  Object.assign(globalThis,{window,document:window.document,HTMLElement:window.HTMLElement,Event:window.Event,requestAnimationFrame:(fn:()=>void)=>fn(),IS_REACT_ACT_ENVIRONMENT:true});
  const {createRoot}=await import('react-dom/client');
  const container=document.createElement('div');document.body.append(container);
  const root=createRoot(container);
  const yesterday=new Date();yesterday.setDate(yesterday.getDate()-1);
  recordCheckin(yesterday);recordCheckin(yesterday);
  assert.deepEqual(readCheckinDates(),[checkinDateKey(yesterday)],'duplicate check-in is idempotent');
  const storage=previewStorage;
  const original=storage.setItem.bind(storage);
  storage.setItem=()=>{throw new Error('quota');};
  assert.throws(()=>recordCheckin(new Date()),/quota/);
  storage.setItem=original;
  assert.deepEqual(readCheckinDates(),[checkinDateKey(yesterday)],'failed write cannot fabricate today');
  let tab:'a'|'b'='a';
  let opened='';
  const props={active:true,tab,onTabChange:(value:'a'|'b')=>{tab=value;},onAddLearning:()=>{},onOpenTargetLibrary:()=>{},onOpenTarget:(id:string)=>{opened=id;},onPolicyChange:()=>{},defaultPolicy:'lightweight' as const,learningTargetCount:1,readyInitialCount:1,reviewCount:0,dailyNewCount:10,learningRecords:[{recordId:'a',targetId:'lend-give' as const,expression:'lend',occurredAt:new Date().toISOString(),kind:'initial_learning' as const,label:'legacy label',detail:'legacy detail'}],onDailyNewCountChange:()=>{}};
  let statsOpened=0;
  const render=async()=>act(()=>root.render(<StudyScreen {...props} tab={tab} onOpenStats={()=>statsOpened++}/>));
  const click=async(text:string)=>{
    const button=[...container.querySelectorAll('button')].find(button=>button.textContent===text);
    assert.ok(button,`button exists: ${text}`);await act(()=>button.click());
  };
  await render();
  await click('学习统计');assert.equal(statsOpened,1);
  assert.ok(!container.textContent?.includes('86'));
  await click('签到今天');
  assert.ok(readCheckinDates().includes(checkinDateKey(new Date())));
  await act(()=>root.render(<div/>));await render();
  assert.ok(container.textContent?.includes('今天已签到'),'check-in survives remount');
  await click('学习偏好');await render();
  assert.ok(container.querySelector('[role="dialog"]'));
  assert.equal(window.location.pathname,'/');
  await click('完成');await render();assert.equal(tab,'a');
  assert.equal(container.querySelector('[role="dialog"]'),null);
  await click('复习');assert.ok(container.textContent?.includes('没有符合条件的内容'));
  await click('全部');
  await act(()=>container.querySelector<HTMLButtonElement>('li button')!.click());assert.equal(opened,'lend-give');
  await act(()=>i18n.changeLanguage('en'));assert.ok(container.textContent?.includes('My learning'));assert.ok(container.textContent?.includes('Check-in calendar'));
  const empty=new Set<'lend-give'>();
  await act(()=>root.render(<LearningTargetLibraryScreen active targetIds={['lend-give']} policyByTarget={{'lend-give':'lightweight'} as never} preparationByTarget={{'lend-give':'ready'} as never} committedTargetIds={empty} completedTargetIds={empty} reviewDueTargetIds={new Set(['lend-give'])} relearningTargetIds={empty} reviewingTargetIds={empty} relearningRepairTargetIds={empty} relearningRetestTargetIds={empty} declaredMasteryTargetIds={empty} onBack={()=>{}} onAddLearning={()=>{}} onOpenTarget={()=>{}}/>));
  assert.ok(container.textContent?.includes('Due for review'));
  const select=container.querySelector('select')!;
  await act(()=>{select.value='new';select.dispatchEvent(new window.Event('change',{bubbles:true}));});
  assert.ok(container.textContent?.includes('No matching content'));
  await act(()=>{select.value='review';select.dispatchEvent(new window.Event('change',{bubbles:true}));});
  assert.equal(container.querySelectorAll('li').length,1);
  await act(()=>root.unmount());window.happyDOM.abort();
  console.log('My learning smoke passed: factual records, preferences, filters, i18n and durable check-ins.');
}
void main();
