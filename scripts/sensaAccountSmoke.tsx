import assert from 'node:assert/strict';
import React, { act } from 'react';
import { Window } from 'happy-dom';
import { ProfileScreen, localPreviewBytes } from '../apps/web/src/experience/components/ProfileScreen';
import i18n from '../apps/web/src/i18n';
async function main() {
  const window = new Window({url:'http://localhost:3000/settings'});
  Object.assign(globalThis,{window,document:window.document,HTMLElement:window.HTMLElement,Event:window.Event,requestAnimationFrame:(fn:()=>void)=>fn(),IS_REACT_ACT_ENVIRONMENT:true});
  const {createRoot}=await import('react-dom/client');
  window.localStorage.setItem('unrelated','private');
  assert.equal(localPreviewBytes(window.localStorage),0);
  const key='sensa:web-ui:v1:example';
  window.localStorage.setItem(key,'abcd');
  assert.equal(localPreviewBytes(window.localStorage),(key.length+4)*2);
  let plans=0;
  const rootElement=document.createElement('div');document.body.append(rootElement);
  const root=createRoot(rootElement);
  const props={active:true,onGoStudyPlan:()=>{plans++;},defaultPolicy:'lightweight' as const,dailyNewCount:10,onPolicyChange:()=>{},onDailyNewCountChange:()=>{}};
  await act(()=>root.render(<ProfileScreen {...props}/>));
  await act(()=>rootElement.querySelector<HTMLButtonElement>('#account-learning-preferences')!.click());
  assert.ok(rootElement.querySelector('[role="dialog"]'));
  assert.equal(window.location.pathname,'/settings');
  await act(()=>document.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape',bubbles:true})));
  assert.equal(rootElement.querySelector('[role="dialog"]'),null);
  assert.equal(document.activeElement?.id,'account-learning-preferences');
  await act(()=>[...rootElement.querySelectorAll('button')].find(button=>button.textContent?.includes('学习计划'))!.click());
  assert.equal(plans,1);
  await act(()=>i18n.changeLanguage('en'));
  assert.ok(rootElement.textContent?.includes('Account & settings'));
  assert.ok(rootElement.textContent?.includes('No account connected'));
  assert.equal(rootElement.querySelectorAll('details').length,3);
  await act(()=>root.unmount());window.happyDOM.abort();
  console.log('Account smoke passed: scoped storage, in-place preferences, focus restoration, plan entry and i18n.');
}
void main();
